// Generates generated/props.json from the @jsonresume/ui sources, so every
// props table in the styleguide comes from the real component types.
// Inherited DOM attributes are summarized rather than listed.
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import docgen from 'react-docgen-typescript';

const here = fileURLToPath(new URL('.', import.meta.url));
const uiRoot = join(here, '../../../packages/ui');
const componentsDir = join(uiRoot, 'src/components');

const files = readdirSync(componentsDir, { recursive: true })
  .map(String)
  .filter((f) => f.endsWith('.tsx') && !f.endsWith('.test.tsx'))
  .map((f) => join(componentsDir, f));

const parser = docgen.withCustomConfig(join(uiRoot, 'tsconfig.json'), {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: true,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) => {
    const source =
      prop.parent?.fileName ?? prop.declarations?.[0]?.fileName ?? '';
    // Keep props declared in the design system. Recipe variants (variant,
    // size, ...) come from a mapped type with no declaration file, so an
    // empty source is ours too. Inherited DOM and Radix attributes are dropped.
    return source === '' || source.includes('packages/ui/src');
  },
});

// '"sm" | "md" | "lg" | undefined' -> ['sm', 'md', 'lg']
function unionValues(type) {
  if (!type) return null;
  const parts = type
    .split('|')
    .map((t) => t.trim())
    .filter((t) => t !== 'undefined');
  return parts.length > 1 && parts.every((t) => /^"[^"]*"$/.test(t))
    ? parts.map((t) => t.slice(1, -1))
    : null;
}

const out = {};
for (const doc of parser.parse(files)) {
  const props = Object.values(doc.props)
    .map((p) => ({
      // Recipe variants have no declaration, and docgen attaches destructured
      // defaults to every same-named prop in a file, so their defaults are
      // unreliable here; the docs state them instead.
      variant: !(p.parent?.fileName ?? p.declarations?.[0]?.fileName),
      name: p.name,
      type: (p.type?.raw ?? p.type?.name ?? 'unknown').replace(
        / \| undefined$/,
        ''
      ),
      values:
        p.type?.name === 'enum'
          ? p.type.value
              .map((v) => v.value)
              .filter((v) => v !== 'undefined')
              .map((v) => v.replace(/^"|"$/g, ''))
          : unionValues(p.type?.name),
      required: p.required,
      defaultValue:
        p.parent?.fileName || p.declarations?.[0]?.fileName
          ? p.defaultValue?.value ?? null
          : null,
      description: p.description ?? '',
    }))
    .sort(
      (a, b) =>
        Number(b.required) - Number(a.required) || a.name.localeCompare(b.name)
    );
  out[doc.displayName] = {
    description: doc.description,
    file: relative(uiRoot, doc.filePath),
    props,
  };
}

mkdirSync(join(here, '../generated'), { recursive: true });
writeFileSync(
  join(here, '../generated/props.json'),
  `${JSON.stringify(out, null, 2)}\n`
);
console.log(`props: ${Object.keys(out).length} components`);

// generated/examples.ts: a static import for every example file, keyed by
// "<component>/<example>", so pages can render examples by id.
const examplesDir = join(here, '../examples');
const exampleIds = readdirSync(examplesDir, { recursive: true })
  .map(String)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) =>
    f
      .replace(/\.tsx$/, '')
      .split('\\')
      .join('/')
  )
  .sort();

const lines = [
  '// Generated by scripts/generate.mjs. Do not edit.',
  "import type { ComponentType } from 'react';",
  ...exampleIds.map((id, i) => `import Example${i} from '../examples/${id}';`),
  '',
  'export const examples: Record<string, ComponentType> = {',
  ...exampleIds.map((id, i) => `  '${id}': Example${i},`),
  '};',
  '',
];
writeFileSync(join(here, '../generated/examples.ts'), lines.join('\n'));
console.log(`examples: ${exampleIds.length}`);
