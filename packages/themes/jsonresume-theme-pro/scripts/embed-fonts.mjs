// Regenerates src/fonts.generated.js from the unmodified Source Serif 4
// WOFF2 files in fonts/ (adobe-fonts/source-serif release 4.005R, TTF/).
// The files are embedded byte-for-byte: subsetting would create a Modified
// Version under the OFL's Reserved Font Name clause.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);

export const FACES = [
  { file: 'SourceSerif4-Regular.ttf.woff2', weight: 400, style: 'normal' },
  { file: 'SourceSerif4-Semibold.ttf.woff2', weight: 600, style: 'normal' },
  { file: 'SourceSerif4-It.ttf.woff2', weight: 400, style: 'italic' },
];

export function generate() {
  const faces = FACES.map(({ file, weight, style }) => {
    const data = readFileSync(new URL(`fonts/${file}`, root)).toString(
      'base64'
    );
    return `  { weight: ${weight}, style: '${style}', data: '${data}' },`;
  });
  return `// Generated by scripts/embed-fonts.mjs. Do not edit.
// Source Serif 4 (c) Adobe, SIL Open Font License 1.1; see fonts/LICENSE.md.
export const FONT_FACES = [
${faces.join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('src/fonts.generated.js', root), generate());
}
